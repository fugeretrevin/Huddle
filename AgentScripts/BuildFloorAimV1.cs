using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using UnityEditor;
using UnityEditor.SceneManagement;
using Oculus.Interaction;
using MuseDesk.Spatial;

/// <summary>
/// Placing the floor office by pointing, scene part. Adds ONE object, "Spatial/FloorAim", with the
/// FloorAimController and the things it draws (all under "FloorAim/Visuals", saved inactive, no
/// colliders, no interactables):
///   AimFootprint (follows the previewed spot): AimFootprintFill (soft translucent rounded rectangle),
///     AimFootprintRim (opaque outline), AimHoldTrack + AimHoldRing (the pinch-and-hold ring);
///   AimCursorLeft / AimCursorRight (a dot where each hand points);
///   AimRayLeft / AimRayRight (LineRenderers: the thin arc from the hand).
/// The meshes are generated by the component at run time, so this builder creates no mesh assets,
/// only two unlit materials (FloorAim_Line opaque, FloorAim_Fill translucent) when they are missing.
/// It wires the controller to the existing SpatialWorkspaceDirector and to the rig's existing hand
/// visuals (OVRHandVisualLeft / OVRHandVisualRight) when they are found; the component finds them by
/// handedness at run time otherwise. Nothing existing is moved, re-parented, deactivated or rewired,
/// and no feature flag is changed. Idempotent; saves the scene once.
///   unity command script run --file AgentScripts/BuildFloorAimV1.cs --entry BuildFloorAimV1.Apply
/// </summary>
public static class BuildFloorAimV1
{
    const string MatDir = "Assets/MuseDesk/Art/Materials/UI";
    static readonly Color Teal = new Color32(0x2F, 0xA3, 0x9A, 0xFF);

    static List<Transform> All() => EditorSceneManager.GetActiveScene().GetRootGameObjects()
        .SelectMany(r => r.GetComponentsInChildren<Transform>(true)).ToList();

    static Transform Holder(Transform parent, string name, int layer, ref int created)
    {
        Transform t = parent.Find(name);
        if (t == null)
        {
            var go = new GameObject(name);
            Undo.RegisterCreatedObjectUndo(go, name);
            go.transform.SetParent(parent, false);
            t = go.transform;
            created++;
        }
        t.gameObject.layer = layer;
        t.localPosition = Vector3.zero;
        t.localRotation = Quaternion.identity;
        t.localScale = Vector3.one;
        return t;
    }

    static T GetOrAdd<T>(GameObject go) where T : Component
    {
        var c = go.GetComponent<T>();
        if (c == null) c = Undo.AddComponent<T>(go);
        return c;
    }

    /// <summary>A child with a MeshFilter (mesh filled in at run time) and a MeshRenderer.</summary>
    static MeshFilter Surface(Transform parent, string name, Material mat, int layer, ref int created)
    {
        Transform t = Holder(parent, name, layer, ref created);
        t.gameObject.SetActive(true);
        var filter = GetOrAdd<MeshFilter>(t.gameObject);
        var r = GetOrAdd<MeshRenderer>(t.gameObject);
        r.sharedMaterial = mat;
        r.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        r.receiveShadows = false;
        r.lightProbeUsage = UnityEngine.Rendering.LightProbeUsage.Off;
        r.reflectionProbeUsage = UnityEngine.Rendering.ReflectionProbeUsage.Off;
        EditorUtility.SetDirty(t.gameObject);
        return filter;
    }

    static LineRenderer Line(Transform parent, string name, Material mat, int layer, ref int created)
    {
        Transform t = Holder(parent, name, layer, ref created);
        t.gameObject.SetActive(true);
        var line = GetOrAdd<LineRenderer>(t.gameObject);
        line.sharedMaterial = mat;
        line.useWorldSpace = true;
        line.positionCount = 0;
        line.startWidth = 0.004f;
        line.endWidth = 0.0025f;
        line.numCapVertices = 2;
        line.alignment = LineAlignment.View;
        line.textureMode = LineTextureMode.Stretch;
        line.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        line.receiveShadows = false;
        line.lightProbeUsage = UnityEngine.Rendering.LightProbeUsage.Off;
        line.reflectionProbeUsage = UnityEngine.Rendering.ReflectionProbeUsage.Off;
        line.enabled = false;
        EditorUtility.SetDirty(t.gameObject);
        return line;
    }

    static void EnsureFolder()
    {
        if (!AssetDatabase.IsValidFolder("Assets/MuseDesk/Art/Materials")) AssetDatabase.CreateFolder("Assets/MuseDesk/Art", "Materials");
        if (!AssetDatabase.IsValidFolder(MatDir)) AssetDatabase.CreateFolder("Assets/MuseDesk/Art/Materials", "UI");
    }

    /// <summary>URP Unlit, two-sided. Translucent when <paramref name="translucent"/>. Created only when missing.</summary>
    static Material Mat(string name, bool translucent, ref int createdMats)
    {
        string path = $"{MatDir}/{name}.mat";
        var m = AssetDatabase.LoadAssetAtPath<Material>(path);
        if (m != null) return m;
        var shader = Shader.Find("Universal Render Pipeline/Unlit");
        if (shader == null) return null;
        EnsureFolder();
        m = new Material(shader);
        Color c = Teal;
        if (translucent) c.a = 0.22f;
        m.SetColor("_BaseColor", c);
        m.SetColor("_Color", c);
        m.SetFloat("_Cull", 0f);                         // seen from either side: the winding cannot hide it
        if (translucent)
        {
            m.SetFloat("_Surface", 1f);                  // Transparent
            m.SetFloat("_Blend", 0f);                    // Alpha
            m.SetFloat("_SrcBlend", (float)UnityEngine.Rendering.BlendMode.SrcAlpha);
            m.SetFloat("_DstBlend", (float)UnityEngine.Rendering.BlendMode.OneMinusSrcAlpha);
            m.SetFloat("_SrcBlendAlpha", (float)UnityEngine.Rendering.BlendMode.One);
            m.SetFloat("_DstBlendAlpha", (float)UnityEngine.Rendering.BlendMode.OneMinusSrcAlpha);
            m.SetFloat("_ZWrite", 0f);
            m.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
            m.SetOverrideTag("RenderType", "Transparent");
            m.SetShaderPassEnabled("DepthOnly", false);
            m.SetShaderPassEnabled("SHADOWCASTER", false);
            m.renderQueue = (int)UnityEngine.Rendering.RenderQueue.Transparent;
        }
        m.enableInstancing = true;
        AssetDatabase.CreateAsset(m, path);
        createdMats++;
        return m;
    }

    public static string Apply()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode) return "BuildFloorAimV1: stop Play Mode first.";
        var scene = EditorSceneManager.GetActiveScene();
        if (!scene.IsValid() || !scene.isLoaded) return "BuildFloorAimV1: no open scene.";

        var all = All();
        Transform spatial = scene.GetRootGameObjects().Select(g => g.transform).FirstOrDefault(t => t.name == "Spatial");
        if (spatial == null) return "BuildFloorAimV1: scene root object \"Spatial\" not found (run BuildSpatialPlacementV1 first); nothing changed.";
        var director = spatial.GetComponentInChildren<SpatialWorkspaceDirector>(true);
        if (director == null) director = Object.FindAnyObjectByType<SpatialWorkspaceDirector>(FindObjectsInactive.Include);
        if (director == null) return "BuildFloorAimV1: no SpatialWorkspaceDirector in the scene; nothing changed.";

        int layer = spatial.gameObject.layer;
        int created = 0, createdMats = 0;
        var matLine = Mat("FloorAim_Line", false, ref createdMats);
        var matFill = Mat("FloorAim_Fill", true, ref createdMats);
        if (matLine == null || matFill == null) return "BuildFloorAimV1: shader \"Universal Render Pipeline/Unlit\" not found; nothing changed.";

        Transform aimT = Holder(spatial, "FloorAim", layer, ref created);
        if (!aimT.gameObject.activeSelf) aimT.gameObject.SetActive(true);
        var aim = GetOrAdd<FloorAimController>(aimT.gameObject);

        Transform visuals = Holder(aimT, "Visuals", layer, ref created);
        visuals.gameObject.SetActive(true);                     // laid out, then switched off below
        Transform foot = Holder(visuals, "AimFootprint", layer, ref created);
        foot.gameObject.SetActive(true);

        aim.director = director;
        aim.visuals = visuals.gameObject;
        aim.footprintRoot = foot;
        aim.footprintFill = Surface(foot, "AimFootprintFill", matFill, layer, ref created);
        aim.footprintRim = Surface(foot, "AimFootprintRim", matLine, layer, ref created);
        aim.holdTrack = Surface(foot, "AimHoldTrack", matLine, layer, ref created);
        aim.holdFill = Surface(foot, "AimHoldRing", matLine, layer, ref created);
        aim.leftCursor = Surface(visuals, "AimCursorLeft", matLine, layer, ref created);
        aim.rightCursor = Surface(visuals, "AimCursorRight", matLine, layer, ref created);
        aim.leftRay = Line(visuals, "AimRayLeft", matLine, layer, ref created);
        aim.rightRay = Line(visuals, "AimRayRight", matLine, layer, ref created);
        aim.footprint = director.footprint;
        aim.footprintCenterOffset = director.floorSettings.footprintCenterOffset;

        // The rig's own hands (no second rig, no new interactor): by name first, then by handedness at run time.
        HandVisual left = null, right = null;
        foreach (var t in all)
        {
            if (t == null) continue;
            if (t.name == "OVRHandVisualLeft" && left == null) left = t.GetComponent<HandVisual>();
            else if (t.name == "OVRHandVisualRight" && right == null) right = t.GetComponent<HandVisual>();
        }
        aim.leftHandVisual = left;
        aim.rightHandVisual = right;

        visuals.gameObject.SetActive(false);                    // no interactables inside: SetActive is safe
        EditorUtility.SetDirty(aim);
        EditorUtility.SetDirty(aimT.gameObject);

        EditorSceneManager.MarkSceneDirty(scene);
        bool saved = EditorSceneManager.SaveScene(scene);
        AssetDatabase.SaveAssets();
        return "BuildFloorAimV1: Spatial/FloorAim " + (created > 0 ? "built (" + created + " objects created)" : "updated (nothing created)")
               + "; materials created=" + createdMats
               + "; director=" + director.gameObject.name
               + "; hands: left=" + (left != null ? "OVRHandVisualLeft" : "found at run time")
               + ", right=" + (right != null ? "OVRHandVisualRight" : "found at run time")
               + "; visuals saved inactive; flags untouched (floor=" + director.flags.floorModeEnabled + ", ceiling=" + director.flags.ceilingModeEnabled + ")"
               + "; scene saved=" + saved;
    }
}
